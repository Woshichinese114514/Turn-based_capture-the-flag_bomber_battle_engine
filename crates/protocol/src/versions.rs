//! 版本号三件套的定义与升级约定。
//!
//! ## 三件套是什么
//!
//! | 版本号 | 位置 | 什么时候 +1 |
//! |---|---|---|
//! | `ENGINE_VERSION` | `protocol::versions` | 模拟核心逻辑变更（例如换掉一个内部数据结构、改变结算顺序但不改规则语义） |
//! | `RULES_VERSION` | `protocol::versions` | **规则**变更：伤害值、复活时长、AP、炸弹倒计时/半径、得分条件、冲突结算规则等 |
//! | `MAP_GEN_VERSION` | `mapgen::MAP_GEN_VERSION` | 地图生成算法变更（同种子会产出不同地图） |
//!
//! ## 为什么必须三件套分开
//!
//! * 两个不同规则版本的对局**不能放在同一份统计里比较**：胜率的变化可能来自规则改动而不是 AI 强弱。
//!   所以 `summary.json` 与回放 `init` 行都要带 `rules_version`，统计/复盘时才能识别批次。
//! * 地图生成版本变了，**同一颗种子会生成不同地图**：旧回放如果按新算法解释地图就会画错。
//!   Web UI 因此需要在 `map_gen_version` 不匹配时给出警告。
//! * 引擎版本用于区分「实现改动」，它不影响成绩可比性，但影响 bug 排查（哪个二进制跑出来的回放）。
//!
//! ## 升级纪律（重要）
//!
//! 1. **只增不改**：规则/算法定型后不要原地修改；需要改就加 `generate_v(N+1)` 并升版本号。
//! 2. **回放格式变更也是协议变更**：新增字段一般可以前向兼容（旧 UI 忽略新字段），
//!    但删字段、改字段含义、改枚举标签都必须升 `engine_version`，并同步更新
//!    `docs/replay-format.md` 与 Web UI 的解析分支。
//! 3. `manifest.json` / `summary.json` / 回放 `init` 行三处都要写这三个版本号，
//!    不允许任何一处缺失（缺失时统计脚本应当报错而不是默认填 0）。

/// 引擎版本：模拟核心实现版本。
///
/// 变更历史（每升一次在这里补一行）：
/// * `1`：初版。回合制、3 单位/队、2~3 队、攻击射程 3、炸弹倒计时 2/半径 2/伤害 2、
///   复活 10 tick、旗刷新间隔 5、中心半径 4。
pub const ENGINE_VERSION: u32 = 1;

/// 规则版本：游戏规则（数值与判定）版本。变更历史：
/// * `1`：初版规则（见 `docs/rules.md` 的数值表）。
pub const RULES_VERSION: u32 = 1;

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn versions_are_positive() {
        // 版本号从 1 开始：0 保留给「未设置/解析失败」的兜底值，避免缺字段和初版混淆。
        //
        // 这里经局部变量断言，而不是直接 `assert!(ENGINE_VERSION >= 1)`：
        // 后者会被 clippy 的 `assertions_on_constants` 判为「断言恒真」而告警。
        // 但这条测试的价值恰恰是「升级版本号的人如果把常量改成 0，CI 立刻红」——
        // 属于有意的编译期契约测试，所以保留断言、只换一种写法。
        let engine = ENGINE_VERSION;
        let rules = RULES_VERSION;
        assert!(engine >= 1);
        assert!(rules >= 1);
    }
}
